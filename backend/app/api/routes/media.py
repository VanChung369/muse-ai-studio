router = APIRouter(prefix="/projects", tags=["Media"])
DatabaseSession = Annotated[Session, Depends(get_session)]

MAX_FILES = 30


class MediaResponse(BaseModel):
    """A video, picture or audio file the user added to a film."""

    model_config = ConfigDict(
        alias_generator=to_camel, validate_by_name=True, from_attributes=True
    )

    id: str
    project_id: str
    kind: Literal["video", "image", "audio"]
    name: str
    mime: str
    size: int
    # Length; null for a picture.
    seconds: float | None
    # Frame size; null for audio.
    width: int | None
    height: int | None
    # "muse": generated by Muse rather than uploaded.
    source: Literal["upload", "muse"]

    @computed_field
    @property
    def url(self) -> str:
        return f"/api/projects/{self.project_id}/media/{self.id}"

    @computed_field
    @property
    def thumbnail_url(self) -> str | None:
        return None if self.kind == "audio" else f"{self.url}/thumbnail"

    @computed_field
    @property
    def waveform_url(self) -> str | None:
        """A drawing of an audio file's sound."""
        return f"{self.url}/waveform" if self.kind == "audio" else None


def error(status: int, code: str, message: str) -> HTTPException:
    return HTTPException(status, detail={"code": code, "message": message})


def _project(session: Session, project_id: str, *, changing: bool = False) -> Project:
    if changing:
        session.execute(
            text("UPDATE projects SET status = status WHERE id = :id"),
            {"id": project_id},
        )
    project = session.get(Project, project_id, populate_existing=changing)
    if project is None:
        raise error(404, "project_not_found", "Project not found.")
    if changing and project.status in ("rendering", "cancelling"):
        raise error(
            409,
            "project_busy",
            "This project is rendering or merging. Wait for it to finish first.",
        )
    return project


def _count(session: Session, project_id: str) -> int:
    return session.scalar(
        select(func.count()).select_from(Media).where(Media.project_id == project_id)
    )


def too_many() -> HTTPException:
    return error(409, "too_many_files", f"A project can hold {MAX_FILES} media files.")


@router.get(
    "/{project_id}/media",
    response_model=list[MediaResponse],
    responses={404: {"description": "Project not found"}},
)
def list_media(project_id: str, session: DatabaseSession):
    return _project(session, project_id).media


@router.post(
    "/{project_id}/media",
    response_model=MediaResponse,
    status_code=201,
    responses={
        404: {"description": "Project not found"},
        409: {"description": "Merging, too many files, or FFmpeg is missing"},
        413: {"description": "File too large"},
        415: {"description": "Not a supported video, picture or audio type"},
        422: {"description": "Empty, or not readable as that kind of media"},
    },
)
async def add_media(
    project_id: str,
    request: Request,
    session: DatabaseSession,
    name: Annotated[str, Query(min_length=1, max_length=200)],
):
    """Upload one file as the raw request body, with its type in Content-Type
    and its original name in `name`."""
    mime = (request.headers.get("content-type") or "").split(";", 1)[0].strip().lower()
    if mime not in TYPES:
        raise error(415, "unsupported_file", "Upload a video, a picture or audio.")
    kind, extension = TYPES[mime]
    settings = request.app.state.settings
    _project(session, project_id, changing=True)
    count = _count(session, project_id)
    session.rollback()  # No transaction is held while the upload streams in.
    if count >= MAX_FILES:
        raise too_many()
    # The file's length and frame size are read once, here.
    ffmpeg = find_ffmpeg(settings)
    if ffmpeg is None:
        raise error(
            409, "ffmpeg_unavailable", "FFmpeg is needed to read uploaded media."
        )

    folder = storage.media_dir(settings, project_id)
    folder.mkdir(parents=True, exist_ok=True)
    file = f"{uuid4().hex}{extension}"
    target, temporary = folder / file, folder / (file + ".part")
    still = folder / thumbnail_name(file)
    size = 0
    try:
        with temporary.open("wb") as stream:
            async for chunk in request.stream():
                size += len(chunk)
                if size > MAX_BYTES:
                    raise error(
                        413, "file_too_large", "A media file can be 200 MB at most."
                    )
                stream.write(chunk)
        if size == 0:
            raise error(422, "empty_file", "The file is empty.")
        os.replace(temporary, target)
    finally:
        temporary.unlink(missing_ok=True)

    try:
        try:
            info = inspect(ffmpeg, target)
        except MergeError:
            info = None
        # The bytes must really be what the type says: a video has a picture
        # and a length, a picture a frame, audio a sound and a length.
        readable = info is not None and (
            (kind == "video" and info.width and info.seconds)
            or (kind == "image" and info.width)
            or (kind == "audio" and info.has_audio and info.seconds)
        )
        if not readable:
            raise error(
                422, "unreadable_file", f"This file could not be read as {kind}."
            )
        if kind != "audio":
            thumbnail(ffmpeg, target, still)  # Best effort; the list copes without.
        media = Media(
            project_id=project_id,
            kind=kind,
            # Only the base name: a path in the name must never reach the disk.
            name=Path(name.replace("\\", "/")).name[:200] or file,
            file=file,
            mime=mime,
            size=size,
            seconds=None if kind == "image" else round(info.seconds, 3),
            width=None if kind == "audio" else info.width,
            height=None if kind == "audio" else info.height,
            source="upload",
        )
        _project(session, project_id, changing=True)
        session.add(media)
        session.flush()
        # Counted again now that this request holds the write lock: uploads
        # that streamed in at the same time cannot all slip past the limit.
        if _count(session, project_id) > MAX_FILES:
            raise too_many()
        session.commit()
        session.refresh(media)
    except Exception:
        session.rollback()
        target.unlink(missing_ok=True)
        still.unlink(missing_ok=True)
        raise
    return media


class MusicRequest(BaseModel):
    model_config = ConfigDict(
        alias_generator=to_camel, extra="forbid", str_strip_whitespace=True
    )
    # The music wanted, in the user's words: mood, instruments, tempo.
    description: str = Field(min_length=1, max_length=500)


@router.post(
    "/{project_id}/media/music",
    response_model=TaskResponse,
    status_code=202,
    responses={
        404: {"description": "Project not found"},
        409: {
            "description": "Music is already being made, no account is usable, "
            "or the project has the most files allowed"
        },
    },
)
def generate_music(
    project_id: str, values: MusicRequest, request: Request, session: DatabaseSession
):
    """Ask Muse for a short piece of background music. It arrives among the
    project's media as an audio file (`source: "muse"`) when the task ends."""
    try:
        task, label = enqueue_music(session, project_id, values.description)
    except MusicRequestError as problem:
        raise error(
            problem.status, problem.code, "Music could not be requested."
        ) from None
    request.app.state.task_coordinator.wake()
    return TaskResponse.from_task(task, label)


@router.get(
    "/{project_id}/media/music",
    response_model=TaskResponse | None,
    responses={404: {"description": "Project not found"}},
)
def get_music_generation(project_id: str, session: DatabaseSession):
    """The latest music request for the project, or null."""
    _project(session, project_id)
    latest = latest_music_task(session, project_id)
    return TaskResponse.from_task(*latest) if latest else None


class LibraryImport(BaseModel):
    model_config = ConfigDict(alias_generator=to_camel, extra="forbid")
    # Library entries to copy into the project: "upload:<id>",
    # "scene:<project id>:<number>" or "film:<project id>".
    ids: list[str] = Field(min_length=1, max_length=20)


@router.post(
    "/{project_id}/media/import",
    response_model=list[MediaResponse],
    status_code=201,
    responses={
        404: {"description": "Project or library entry not found"},
        409: {"description": "Merging, too many files, or FFmpeg is missing"},
    },
)
def import_media(
    project_id: str, values: LibraryImport, request: Request, session: DatabaseSession
):
    """Copy files from the media library into the project's media. The
    project gets copies of its own, so it does not depend on the library."""
    settings = request.app.state.settings
    _project(session, project_id, changing=True)
    wanted = list(dict.fromkeys(values.ids))
    if _count(session, project_id) + len(wanted) > MAX_FILES:
        raise too_many()
    items = [library.find(session, settings, item_id) for item_id in wanted]
    session.rollback()  # No transaction is held while files are copied.
    if not all(items):
        raise error(
            404, "library_item_not_found", "One of these files is not in the library."
        )
    ffmpeg = find_ffmpeg(settings)
    # An uploaded file was measured when it arrived; a clip made in Video
    # Studio has to be read now.
    if ffmpeg is None and any(item.role != "upload" for item in items):
        raise error(409, "ffmpeg_unavailable", "FFmpeg is needed to read this video.")

    folder = storage.media_dir(settings, project_id)
    folder.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    created: list[Media] = []
    try:
        for item in items:
            extension = TYPES.get(item.mime, (None, item.path.suffix))[1]
            file = f"{uuid4().hex}{extension}"
            target, still = folder / file, folder / thumbnail_name(file)
            written += [target, still]
            shutil.copyfile(item.path, target)
            seconds, width, height = item.seconds, item.width, item.height
            if item.role != "upload":
                try:
                    info = inspect(ffmpeg, target)
                except MergeError:
                    info = None
                if not readable(info, item.kind):
                    raise error(
                        404,
                        "library_item_not_found",
                        "One of these files could not be read.",
                    )
                seconds, width, height = round(info.seconds, 3), info.width, info.height
            if item.kind != "audio":
                made = library.still_of(item)
                if made is not None:
                    shutil.copyfile(made, still)
                elif ffmpeg:
                    thumbnail(ffmpeg, target, still)  # Best effort.
            created.append(
                Media(
                    project_id=project_id,
                    kind=item.kind,
                    name=base_name(item.file_name, file),
                    file=file,
                    mime=item.mime,
                    size=target.stat().st_size,
                    seconds=None if item.kind == "image" else seconds,
                    width=None if item.kind == "audio" else width,
                    height=None if item.kind == "audio" else height,
                    source="upload",
                )
            )
        _project(session, project_id, changing=True)
        session.add_all(created)
        session.flush()
        # Counted again now that this request holds the write lock.
        if _count(session, project_id) > MAX_FILES:
            raise too_many()
        session.commit()
        for media in created:
            session.refresh(media)
    except Exception:
        session.rollback()
        for path in written:
            path.unlink(missing_ok=True)
        raise
    return created


def _media(session: Session, project_id: str, media_id: str) -> Media:
    media = session.get(Media, media_id)
    if media is None or media.project_id != project_id:
        raise error(404, "media_not_found", "Media file not found.")
    return media


def _serve(path: Path, mime: str) -> FileResponse:
    if not path.is_file():
        raise error(404, "media_not_found", "Media file not found.")
    return FileResponse(
        path,
        media_type=mime,
        headers={
            "Cache-Control": "private, max-age=3600",
            # The type was declared by the uploader: never let a browser
            # guess a different one from the bytes.
            "X-Content-Type-Options": "nosniff",
        },
    )


@router.get(
    "/{project_id}/media/{media_id}",
    response_class=FileResponse,
    responses={404: {"description": "Project or file not found"}},
)
def get_media(
    project_id: str, media_id: str, request: Request, session: DatabaseSession
):
    media = _media(session, project_id, media_id)
    path = storage.media_dir(request.app.state.settings, project_id) / media.file
    mime = media.mime
    session.rollback()
    return _serve(path, mime)


@router.get(
    "/{project_id}/media/{media_id}/thumbnail",
    response_class=FileResponse,
    responses={404: {"description": "No still for this file"}},
)
def get_media_thumbnail(
    project_id: str, media_id: str, request: Request, session: DatabaseSession
):
    media = _media(session, project_id, media_id)
    folder = storage.media_dir(request.app.state.settings, project_id)
    kind, file, mime = media.kind, media.file, media.mime
    session.rollback()
    still = folder / thumbnail_name(file)
    if still.is_file():
        return _serve(still, "image/jpeg")
    if kind == "image":
        return _serve(folder / file, mime)  # No still was made: the picture itself.
    raise error(404, "media_not_found", "This file has no still.")


@router.get(
    "/{project_id}/media/{media_id}/waveform",
    response_class=FileResponse,
    responses={404: {"description": "Not audio, or it could not be drawn"}},
)
def get_media_waveform(
    project_id: str, media_id: str, request: Request, session: DatabaseSession
):
    """The sound of an audio file drawn as a wide, see-through PNG."""
    media = _media(session, project_id, media_id)
    settings = request.app.state.settings
    folder = storage.media_dir(settings, project_id)
    kind, file = media.kind, media.file
    session.rollback()
    drawing = folder / waveform_name(file)
    if kind == "audio" and not drawing.is_file():
        # Drawn the first time it is asked for, then kept.
        ffmpeg = find_ffmpeg(settings)
        if ffmpeg:
            waveform(ffmpeg, folder / file, drawing)
    if kind != "audio" or not drawing.is_file():
        raise error(404, "media_not_found", "This file has no waveform.")
    return _serve(drawing, "image/png")


@router.delete(
    "/{project_id}/media/{media_id}",
    status_code=204,
    response_class=Response,
    responses={
        404: {"description": "Project or file not found"},
        409: {"description": "Merging, or the file is used in the film"},
    },
)
def delete_media(
    project_id: str, media_id: str, request: Request, session: DatabaseSession
):
    project = _project(session, project_id, changing=True)
    media = _media(session, project_id, media_id)
    if timeline.uses(project, media_id):
        # Deleting it would change the film behind the editor's back.
        raise error(
            409, "media_in_use", "This file is used in the film. Remove it there first."
        )
    folder = storage.media_dir(request.app.state.settings, project_id)
    file = media.file
    try:
        session.delete(media)
        session.commit()
    except Exception:
        session.rollback()
        raise
    (folder / file).unlink(missing_ok=True)
    (folder / thumbnail_name(file)).unlink(missing_ok=True)
    (folder / waveform_name(file)).unlink(missing_ok=True)
    return Response(status_code=204)
